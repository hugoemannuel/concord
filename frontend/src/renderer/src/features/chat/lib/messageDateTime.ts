/** Data e hora locais usadas nas mensagens, com a pontuação do formato completo. */
export function formatMessageDateTime(iso: string): string {
  return new Date(iso).toLocaleString('pt-BR', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  })
}
